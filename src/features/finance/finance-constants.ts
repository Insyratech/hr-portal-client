export function optionalFormString(value: FormDataEntryValue | null): string | null {
  const trimmed = String(value ?? '').trim();
  return trimmed ? trimmed : null;
}

export function stateFromCode(code: string | null | undefined): { stateCode: string | null; stateName: string | null } {
  const trimmed = (code ?? '').trim();
  if (!trimmed) return { stateCode: null, stateName: null };
  const match = INDIAN_STATES.find((state) => state.code === trimmed);
  return { stateCode: trimmed, stateName: match?.name ?? null };
}
